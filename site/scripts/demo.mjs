//   ["tick", text]               one more line in the live reply: what the agent just did
//   ["answer", text]             the live reply becomes the answer, in place
//   ["stopped", text]            the live reply ends without an answer
//   ["typing"]                   the app's typing indicator, then the next "say"
//   ["say", text]                the agent sends a message
//   ["toast", text]              the closing note, like "Sent on Discord"
